# ---------------------------------------------------------------------------
# STEP 1 — For each section, create a 1920×1080 PNG with screenshot + overlay
# ---------------------------------------------------------------------------

def esc(s):
    """Escape text for ffmpeg drawtext."""
    return s.replace("'", "\\'").replace(":", "\\:").replace(",", "\\,")

def make_slide(section_idx, img_path, hold_sec, title, subtitle, out_png):
    """Create a static slide PNG using ffmpeg."""

    # Background: scale screenshot to cover 1920x1080, or black card
    if img_path and os.path.exists(img_path):
        input_part = ['-i', img_path]
        scale_filter = (
            f'[0:v]scale={W}:{H}:force_original_aspect_ratio=increase,'
            f'crop={W}:{H}[bg];'
        )
        base_ref = '[bg]'
    else:
        # Black card
        input_part = ['-f', 'lavfi', '-i', f'color=c=0x0d1b2a:size={W}x{H}:r=1']
        scale_filter = '[0:v]'
        base_ref = '[0:v]'

    # Dark overlay for text legibility
    overlay_filter = (
        f"{base_ref}"
        f"drawbox=x=0:y={H-160}:w={W}:h=160:color=0x0d1b2a@0.85:t=fill,"
    )

    # Section label bar at top
    label_y = 40
    label_filter = (
        f"drawbox=x=0:y=0:w={W}:h=70:color=0x0a3d62@0.92:t=fill,"
        f"drawtext=fontfile='C\\:/Windows/Fonts/segoeui.ttf':text='{esc(title)}':"
        f"fontsize=34:fontcolor=0xffffff:x=60:y=20:shadowx=2:shadowy=2,"
    )

    # Subtitle at bottom
    sub_filter = (
        f"drawtext=fontfile='C\\:/Windows/Fonts/segoeui.ttf':text='{esc(subtitle)}':"
        f"fontsize=26:fontcolor=0xaabbcc:x=60:y={H-100}:shadowx=1:shadowy=1"
    )

    # For pure title cards (intro/outro), center everything
    if not img_path or not os.path.exists(img_path):
        overlay_filter = f"[0:v]"
        label_filter = (
            f"drawbox=x=0:y=0:w={W}:h={H}:color=0x0d1b2a@1.0:t=fill,"
            # KaiMS big logo text
            f"drawtext=fontfile='C\\:/Windows/Fonts/segoeuib.ttf':text='KaiMS':"
            f"fontsize=110:fontcolor=0x00b4d8:x=(w-tw)/2:y=(h/2)-140:shadowx=4:shadowy=4,"
            # tagline
            f"drawtext=fontfile='C\\:/Windows/Fonts/segoeui.ttf':text='{esc(subtitle)}':"
            f"fontsize=30:fontcolor=0xadd8e6:x=(w-tw)/2:y=(h/2):shadowx=2:shadowy=2,"
        )
        label_filter += (
            f"drawtext=fontfile='C\\:/Windows/Fonts/segoeui.ttf':text='AI Operations Command Center':"
            f"fontsize=36:fontcolor=0xffffff:x=(w-tw)/2:y=(h/2)-60:shadowx=2:shadowy=2"
        )
        vf = overlay_filter + label_filter
    else:
        vf = scale_filter + overlay_filter + label_filter + sub_filter

    cmd = [
        FFMPEG, '-y',
        *input_part,
        '-vf', vf,
        '-frames:v', '1',
        out_png,
    ]
    result = subprocess.run(cmd, capture_output=True, text=True, encoding='utf-8', errors='replace')
    if result.returncode != 0:
        print(f"  [ERR] slide {section_idx}: {result.stderr[-400:]}")
        return False
    return True


print("\n=== Building slides ===")
slide_paths = []
for idx, (img_name, hold, title, subtitle) in enumerate(SECTIONS):
    img_path = os.path.join(PAGES_DIR, img_name) if img_name else None
    out_png  = os.path.join(SCRATCH, f'slide_{idx:02d}.png')
    ok = make_slide(idx, img_path, hold, title, subtitle, out_png)
    slide_paths.append((out_png, hold, ok))
    status = "OK" if ok else "FAIL"
    print(f"  [{status}] slide {idx:02d} — {title}")

# ---------------------------------------------------------------------------
# STEP 2 — Create a video segment per slide (hold + fade-out last 0.5s)
# ---------------------------------------------------------------------------
print("\n=== Building segments ===")
seg_paths = []
FADE_DUR = 0.5

for idx, (png, hold, ok) in enumerate(slide_paths):
    seg = os.path.join(SCRATCH, f'seg_{idx:02d}.mp4')
    total_frames = int(hold * FPS)
    fade_start   = hold - FADE_DUR

    vf = (
        f'fade=t=in:st=0:d={FADE_DUR}:color=black,'
        f'fade=t=out:st={fade_start}:d={FADE_DUR}:color=black'
    )

    cmd = [
        FFMPEG, '-y',
        '-loop', '1', '-i', png,
        '-t', str(hold),
        '-vf', vf,
        '-r', str(FPS),
        '-pix_fmt', 'yuv420p',
        '-c:v', 'libx264', '-preset', 'fast', '-crf', '18',
        seg,
    ]
    result = subprocess.run(cmd, capture_output=True, text=True, encoding='utf-8', errors='replace')
    if result.returncode != 0:
        print(f"  [ERR] seg {idx}: {result.stderr[-300:]}")
    else:
        seg_paths.append(seg)
        print(f"  [OK] seg_{idx:02d}.mp4  ({hold}s)")

# ---------------------------------------------------------------------------
# STEP 3 — Concatenate all segments
# ---------------------------------------------------------------------------
print("\n=== Concatenating segments ===")
concat_list = os.path.join(SCRATCH, 'concat.txt')
with open(concat_list, 'w', encoding='utf-8') as f:
    for seg in seg_paths:
        f.write(f"file '{seg}'\n")

cmd = [
    FFMPEG, '-y',
    '-f', 'concat', '-safe', '0',
    '-i', concat_list,
    '-c', 'copy',
    OUT_VIDEO,
]
result = subprocess.run(cmd, capture_output=True, text=True, encoding='utf-8', errors='replace')
if result.returncode == 0:
    size_mb = os.path.getsize(OUT_VIDEO) / (1024*1024)
    print(f"\n[SUCCESS] Output: {OUT_VIDEO}")
    print(f"  Size: {size_mb:.1f} MB")
    # Get duration
    probe = subprocess.run(
        [FFPROBE, '-v', 'error', '-show_entries', 'format=duration',
         '-of', 'default=noprint_wrappers=1:nokey=1', OUT_VIDEO],
        capture_output=True, text=True
    )
    dur = float(probe.stdout.strip() or 0)
    print(f"  Duration: {dur:.1f}s ({int(dur)//60}m {int(dur)%60}s)")
else:
    print(f"[FAIL] concat error: {result.stderr[-500:]}")
